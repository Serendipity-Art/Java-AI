public class HelloWorld {
    public static void main(String[] args){
        //String [] args：main() 方法的参数，类型为 String 数组，参数名为 args
        System.out.printf("HelloWorld");
        //System.out.println()：一个 Java 语句，一般情况下是将传递的参数打印到控制台。
        // System 是 java.lang 包中的一个 final 类，该类提供的设施包括标准输入，标准输出和错误输出流等等。
        // out 是 System 类的静态成员字段，类型为 PrintStream，
        // 它与主机的标准输出控制台进行映射。println 是 PrintStream 类的一个方法，
        // 通过调用 print 方法并添加一个换行符实现的。
    }
}
